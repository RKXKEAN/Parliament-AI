_MAX_CHARS = 120_000


def summarize_transcript(
    transcript: str,
    api_key: str,
    mode: str = "full_report",
    model_name: str = "google/gemini-2.0-flash-001",
    provider: str = "openrouter",
) -> str:
    if len(transcript) > _MAX_CHARS:
        transcript = transcript[:_MAX_CHARS] + "\n\n[…ข้อความถูกตัดเนื่องจากยาวเกินไป]"

    prompt = MODE_PROMPTS.get(mode, MODE_PROMPTS["full_report"]).format(
        transcript=transcript
    )

    return _call_openrouter(api_key, model_name, prompt)


def _call_openrouter(api_key: str, model_name: str, prompt: str) -> str:
    import requests, json as _json

    # HTTP headers ต้องเป็น ASCII เท่านั้น — ห้ามใส่อักขระไทยหรือ em-dash
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json; charset=utf-8",
        "HTTP-Referer": "https://parliament-ai.local",
        "X-Title": "Parliament AI",  # ASCII only — no Thai, no em-dash
    }

    # ส่ง body เป็น bytes utf-8 แทน ให้ requests ไม่ต้อง encode เอง
    body = _json.dumps(
        {
            "model": model_name,
            "temperature": 0.2,
            "max_tokens": 8192,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
        },
        ensure_ascii=False,
    ).encode("utf-8")

    resp = requests.post(
        url="https://openrouter.ai/api/v1/chat/completions",
        headers=headers,
        data=body,  # ใช้ data= (bytes) แทน json= เพื่อควบคุม encoding เอง
        timeout=180,
    )

    resp.encoding = "utf-8"
    if resp.status_code != 200:
        raise RuntimeError(f"OpenRouter error {resp.status_code}: {resp.text[:400]}")

    return resp.json()["choices"][0]["message"]["content"]
