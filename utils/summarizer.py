_MAX_CHARS = 120_000


def summarize_transcript(
    transcript: str,
    api_key: str,
    mode: str = "full_report",
    model_name: str = "gemini-2.0-flash",
    provider: str = "gemini",
) -> str:
    if len(transcript) > _MAX_CHARS:
        transcript = transcript[:_MAX_CHARS] + "\n\n[…ข้อความถูกตัดเนื่องจากยาวเกินไป]"

    prompt = MODE_PROMPTS.get(mode, MODE_PROMPTS["full_report"]).format(
        transcript=transcript
    )

    if provider == "openrouter":
        return _call_openrouter(api_key, model_name, prompt)
    return _call_gemini(api_key, model_name, prompt)


def _call_gemini(api_key: str, model_name: str, prompt: str) -> str:
    try:
        import google.generativeai as genai
    except ImportError:
        raise ImportError("กรุณาติดตั้ง:  pip install google-generativeai")

    genai.configure(api_key=api_key)
    model = genai.GenerativeModel(
        model_name=model_name,
        system_instruction=SYSTEM_PROMPT,
        generation_config={
            "temperature": 0.2,
            "top_p": 0.85,
            "max_output_tokens": 8192,
        },
        safety_settings=[
            {"category": c, "threshold": "BLOCK_NONE"}
            for c in [
                "HARM_CATEGORY_HARASSMENT",
                "HARM_CATEGORY_HATE_SPEECH",
                "HARM_CATEGORY_SEXUALLY_EXPLICIT",
                "HARM_CATEGORY_DANGEROUS_CONTENT",
            ]
        ],
    )
    result = model.generate_content(prompt).text
    # sanitize unicode to prevent codec errors downstream
    return result.encode("utf-8", errors="replace").decode("utf-8")


def _call_openrouter(api_key: str, model_name: str, prompt: str) -> str:
    import requests, json as _json

    # HTTP headers ต้องเป็น ASCII เท่านั้น — ห้ามใส่อักขระไทยหรือ em-dash
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json; charset=utf-8",
        "HTTP-Referer": "https://parliament-ai.local",
        "X-Title": "Parliament AI",  # ASCII only — no Thai, no em-dash
    }

    # ส่ง body เป็น bytes utf-8 แทน ให้ requests ไม่ต้อง encode เอง
    body = _json.dumps(
        {
            "model": model_name,
            "temperature": 0.2,
            "max_tokens": 8192,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
        },
        ensure_ascii=False,
    ).encode("utf-8")

    resp = requests.post(
        url="https://openrouter.ai/api/v1/chat/completions",
        headers=headers,
        data=body,  # ใช้ data= (bytes) แทน json= เพื่อควบคุม encoding เอง
        timeout=180,
    )

    resp.encoding = "utf-8"
    if resp.status_code != 200:
        raise RuntimeError(f"OpenRouter error {resp.status_code}: {resp.text[:400]}")

    return resp.json()["choices"][0]["message"]["content"]
